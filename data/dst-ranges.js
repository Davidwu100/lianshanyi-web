/*!
 * 连山易 · 中国夏令时（夏时制）区间表（dst.js）
 * ---------------------------------------------------------------------------
 * 为什么需要这个表
 *   夏令时（Daylight Saving Time）是**人为把时钟拨快一小时**的行政干预。
 *   语料 GE萃取2:4579「天道运行不因人事而变：地球自转与太阳光照的相对位置
 *   不会因为人类更改时钟而发生变化。」
 *   → 排盘所依据的应是**真实的物理平太阳时**，故须把行政拨快的那一小时还原。
 *
 * 语料依据（GE萃取2，三处一致）
 *   4580「**必须强制剔除**：凡是判定出生于夏令时实行期间的时间，必须在系统底层
 *        强制减去 1 小时，还原为该地区真实的物理平太阳时……否则有极高概率导致
 *        『时柱』甚至『日柱（23点临界）』排错。」
 *   4581「中国在 1986 至 1991 年期间实行过夏令时。若用户输入 1988年5月12日 21:00，
 *        系统检测到该时间处于中国夏令时区间，应自动在后台扣除一小时，
 *        按 20:00（戌时）进行四柱推导和命卦计算。」
 *   4625 精确用例「1988年5月12日 21:30（中国）→ 物理平太阳时自动校正为 20:30。
 *        时柱使用：丙戌时（未校正则为丁亥时）。」
 *   5079「若出生于 1986 至 1991 年中国实行夏令时期间，系统后台强制将录入时间
 *        自动 −1 小时，还原为真实的物理平太阳时。」
 *
 * ⚠ 语料**未给精确起止日**，只有「1986 至 1991 年期间」。
 *   本表的精确日期取自 1986 年中央有关部门《在全国范围内实行夏时制的通知》的
 *   公开转述（澎湃新闻《那些年，我国也实行过夏时制》）：
 *     规则：自 1986 年起，每年 **4 月中旬第一个星期日** 凌晨 2:00（北京时间）
 *           拨快 1 小时开始；**9 月中旬第一个星期日** 凌晨 2:00（北京夏令时）
 *           拨回 1 小时结束。
 *     例外：**1986 年为首年，实际自 5 月 4 日开始、至 9 月 14 日结束**。
 *   该来源并明确记载「在夏时制实行期间出生的婴儿，**登记出生时间时要减去一小时**」，
 *   与语料 4580 口径一致。
 *   1992 年起暂停实行 → 1992 及以后**无夏令时**。
 *
 * ⚠ 适用范围：**中国大陆**（1986-1991 全国统一施行）。境外出生不适用本表。
 * ---------------------------------------------------------------------------
 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.LSY = root.LSY || {};
    root.LSY.data = root.LSY.data || {};
    root.LSY.data.dst = factory();
  }
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  // [年份, 开始月, 开始日, 结束月, 结束日]
  //   开始日 = 该年 4 月中旬第一个星期日；结束日 = 该年 9 月中旬第一个星期日
  //   1986 为首年例外（5/4 – 9/14）
  var RANGES = [
    [1986, 5, 4, 9, 14],
    [1987, 4, 12, 9, 13],
    [1988, 4, 10, 9, 11],
    [1989, 4, 16, 9, 17],
    [1990, 4, 15, 9, 16],
    [1991, 4, 14, 9, 15]
  ];

  var OFFSET_MINUTES = -60;   // 行政拨快 1 小时 → 还原须 −1 小时

  /** 某公历日期是否处于中国大陆夏令时期间 */
  function inDst(year, month, day) {
    for (var i = 0; i < RANGES.length; i++) {
      var r = RANGES[i];
      if (r[0] !== year) continue;
      var v = month * 100 + day;
      return v >= r[1] * 100 + r[2] && v <= r[3] * 100 + r[4];
    }
    return false;
  }

  /** 该年的夏令时区间（无则 null） */
  function rangeOf(year) {
    for (var i = 0; i < RANGES.length; i++) if (RANGES[i][0] === year) return RANGES[i];
    return null;
  }

  return {
    RANGES: RANGES,
    OFFSET_MINUTES: OFFSET_MINUTES,
    YEARS: RANGES.map(function (r) { return r[0]; }),
    inDst: inDst,
    rangeOf: rangeOf,
    _status: 'confirmed',
    _scope: '中国大陆（1986–1991 全国统一施行）；境外出生不适用',
    _sources: [
      'GE萃取2-260908 X.md:4580（强制剔除 −1 小时）',
      'GE萃取2-260908 X.md:4581（1986–1991，含 1988-05-12 21:00→20:00 用例）',
      'GE萃取2-260908 X.md:4625（1988-05-12 21:30→20:30，时柱 丁亥→丙戌）',
      'GE萃取2-260908 X.md:5079（1986–1991 强制 −1 小时）',
      '1986 年中央有关部门《在全国范围内实行夏时制的通知》公开转述'
        + '（澎湃新闻《那些年，我国也实行过夏时制》）：'
        + '自 1986 年起每年 4 月中旬第一个星期日 2:00 开始、'
        + '9 月中旬第一个星期日 2:00 结束；1986 年为首年例外（5/4–9/14）；1992 年起暂停'
    ],
    _note: '语料仅给「1986–1991 年期间」，精确起止日取自上述通知的公开转述。'
      + '若日后取得通知原件，应以其为准并更新本表。'
  };
});
